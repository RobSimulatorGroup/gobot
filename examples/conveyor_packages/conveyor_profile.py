def quality_profile(name: str | None = None) -> ConveyorQualityProfile:
    selected = (
        name
        if name is not None
        else os.environ.get(QUALITY_ENVIRONMENT_VARIABLE, "interactive")
    )
    selected = str(selected).strip().lower()
    try:
        return QUALITY_PROFILES[selected]
    except KeyError as error:
        choices = ", ".join(repr(value) for value in QUALITY_PROFILES)
        raise ValueError(
            f"{QUALITY_ENVIRONMENT_VARIABLE} must be one of {choices}"
        ) from error


def smoothstep(value: float) -> float:
    value = max(0.0, min(1.0, float(value)))
    return value * value * (3.0 - 2.0 * value)


def belt_speed_at_tick(tick: int) -> float:
    tick = max(0, int(tick))
    if tick < BELT_START_TICKS:
        return 0.0
    tick -= BELT_START_TICKS
    if tick < RAMP_TICKS:
        return BELT_SPEED * smoothstep(float(tick + 1) / RAMP_TICKS)
    tick -= RAMP_TICKS
    if tick < CONVEY_TICKS:
        return BELT_SPEED
    tick -= CONVEY_TICKS
    if tick < BRAKE_TICKS:
        return BELT_SPEED * (
            1.0 - smoothstep(float(tick + 1) / BRAKE_TICKS)
        )
    return 0.0


def _lerp_targets(
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
    fraction: float,
) -> tuple[tuple[float, ...], ...]:
    return tuple(
        tuple(
            start_value + (end_value - start_value) * fraction
            for start_value, end_value in zip(
                start_hand, end_hand, strict=True
            )
        )
        for start_hand, end_hand in zip(start, end, strict=True)
    )


def _transition(
    tick: int,
    duration: int,
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    fraction = smoothstep(float(tick + 1) / duration)
    return _lerp_targets(start, end, fraction)


def _pivot_roll_transition(
    tick: int,
    duration: int,
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    """Roll each wrist through 180 degrees about a fixed fingertip point."""
    fraction = smoothstep(float(tick + 1) / duration)
    targets = []
    for start_hand, end_hand in zip(start, end, strict=True):
        roll_delta = end_hand[3] - start_hand[3]
        angle = roll_delta * fraction
        cosine = math.cos(angle)
        sine = math.sin(angle)
        pivot_y = 0.5 * (start_hand[1] + end_hand[1])
        pivot_z = 0.5 * (start_hand[2] + end_hand[2])
        offset_y = pivot_y - start_hand[1]
        offset_z = pivot_z - start_hand[2]
        rotated_y = cosine * offset_y - sine * offset_z
        rotated_z = sine * offset_y + cosine * offset_z
        linear = tuple(
            start_value + (end_value - start_value) * fraction
            for start_value, end_value in zip(
                start_hand, end_hand, strict=True
            )
        )
        targets.append(
            (
                linear[0],
                pivot_y - rotated_y,
                pivot_z - rotated_z,
                linear[3],
                linear[4],
                linear[5],
            )
        )
    return tuple(targets)


def _motion_segment_at_tick(
    tick: int,
) -> tuple[HandMotionSegment | None, int]:
    local_tick = max(0, int(tick))
    for segment in HAND_MOTION_SEGMENTS:
        if local_tick < segment.duration:
            return segment, local_tick
        local_tick -= segment.duration
    return None, 0


def hand_stage_targets_at_tick(
    tick: int,
) -> tuple[tuple[float, ...], ...]:
    segment, local_tick = _motion_segment_at_tick(tick)
    if segment is None:
        return HAND_MOTION_SEGMENTS[-1].end
    transition = _pivot_roll_transition if segment.pivot_roll else _transition
    return transition(
        local_tick,
        segment.duration,
        segment.start,
        segment.end,
    )


def _finger_close_pair(
    value: float | tuple[float, float],
) -> tuple[float, float]:
    if isinstance(value, tuple):
        if len(value) != 2:
            raise ValueError("finger close target must contain two hands")
        return (float(value[0]), float(value[1]))
    scalar = float(value)
    return (scalar, scalar)


def finger_close_fractions_at_tick(tick: int) -> tuple[float, float]:
    segment, local_tick = _motion_segment_at_tick(tick)
    if segment is None:
        return (0.0, 0.0)
    fraction = smoothstep(float(local_tick + 1) / segment.duration)
    close_start = _finger_close_pair(segment.close_start)
    close_end = _finger_close_pair(segment.close_end)
    return tuple(
        start + (end - start) * fraction
        for start, end in zip(close_start, close_end, strict=True)
    )


def finger_close_fraction_at_tick(tick: int) -> float:
    """Return the strongest hand closure for compact UI diagnostics."""
    return max(finger_close_fractions_at_tick(tick))


def hand_controls_at_tick(tick: int) -> tuple[tuple[float, ...], ...]:
    stage_targets = hand_stage_targets_at_tick(tick)
    close_fractions = finger_close_fractions_at_tick(tick)
    return tuple(
        stage
        + tuple(
            value * close_fraction for value in LEAP_FINGER_CLOSE_TARGETS
        )
        for stage, close_fraction in zip(
            stage_targets, close_fractions, strict=True
        )
    )


def cycle_phase(tick: int) -> str:
    segment, _ = _motion_segment_at_tick(tick)
    return segment.phase if segment is not None else "settle"
