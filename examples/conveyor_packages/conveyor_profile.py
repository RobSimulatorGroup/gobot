def _retarget_flip_targets(
    targets: tuple[tuple[float, ...], ...],
    *,
    x_shift: float,
    y_shift: float,
    z_shift: float,
    width_inset: float,
    roll_offset: float,
) -> tuple[tuple[float, ...], ...]:
    return tuple(
        (
            target[0] + x_shift + (width_inset if index == 0 else -width_inset),
            target[1] + y_shift,
            target[2] + z_shift,
            target[3] + roll_offset,
            target[4],
            target[5],
        )
        for index, target in enumerate(targets)
    )


def _high_transfer_targets(
    targets: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    """Keep lateral/rotational targeting while moving both wrists high."""
    return tuple(
        (target[0], target[1], 0.15, *target[3:]) for target in targets
    )


def _limit_side_preload(
    targets: tuple[tuple[float, ...], ...],
    approach: tuple[tuple[float, ...], ...],
    preload: float,
) -> tuple[tuple[float, ...], ...]:
    return tuple(
        (
            approach_target[0] + (preload if index == 0 else -preload),
            *target[1:],
        )
        for index, (target, approach_target) in enumerate(
            zip(targets, approach, strict=True)
        )
    )


def _offset_hand_targets(
    targets: tuple[tuple[float, ...], ...],
    offsets: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    """Apply an independent Cartesian offset to each wrist target."""
    return tuple(
        tuple(
            value + offset
            for value, offset in zip(target, hand_offset, strict=True)
        )
        for target, hand_offset in zip(targets, offsets, strict=True)
    )


