QUALITY_ENVIRONMENT_VARIABLE = "GOBOT_CONVEYOR_QUALITY"


@dataclass(frozen=True)
class ConveyorQualityProfile:
    name: str
    coupling_iterations: int
    relaxation_mode: str
    scene_sync_interval: int
    contact_refresh_interval: int
    newton_max_iterations: int
    line_search_max_iterations: int
    linear_system_tolerance_rate: float
    strict_convergence: bool


QUALITY_PROFILES = {
    "interactive": ConveyorQualityProfile(
        name="interactive",
        coupling_iterations=1,
        relaxation_mode="fixed",
        scene_sync_interval=2,
        contact_refresh_interval=4,
        # The thin shell repeatedly enters dense finger contact while it is
        # flipped. Most frames converge within 12 iterations, but the contact
        # transitions need more nonlinear iterations to reach the same 0.1 mm
        # displacement tolerance. Keep the faster interactive linear solve;
        # Newton exits early on ordinary frames, so this is only a safety cap.
        newton_max_iterations=32,
        line_search_max_iterations=8,
        linear_system_tolerance_rate=2.0e-3,
        strict_convergence=False,
    ),
    "accurate": ConveyorQualityProfile(
        name="accurate",
        coupling_iterations=2,
        relaxation_mode="aitken",
        scene_sync_interval=1,
        contact_refresh_interval=1,
        newton_max_iterations=16,
        line_search_max_iterations=8,
        linear_system_tolerance_rate=1.0e-3,
        strict_convergence=True,
    ),
}


def quality_profile(name: str | None = None) -> ConveyorQualityProfile:
    selected = (
        name
        if name is not None
        else os.environ.get(QUALITY_ENVIRONMENT_VARIABLE, "interactive")
    )
    selected = str(selected).strip().lower()
    try:
        return QUALITY_PROFILES[selected]
    except KeyError as error:
        choices = ", ".join(repr(value) for value in QUALITY_PROFILES)
        raise ValueError(
            f"{QUALITY_ENVIRONMENT_VARIABLE} must be one of {choices}"
        ) from error


def smoothstep(value: float) -> float:
    value = max(0.0, min(1.0, float(value)))
    return value * value * (3.0 - 2.0 * value)


def belt_speed_at_tick(tick: int) -> float:
    tick = max(0, int(tick))
    if tick < BELT_START_TICKS:
        return 0.0
    tick -= BELT_START_TICKS
    if tick < RAMP_TICKS:
        return BELT_SPEED * smoothstep(float(tick + 1) / RAMP_TICKS)
    tick -= RAMP_TICKS
    if tick < CONVEY_TICKS:
        return BELT_SPEED
    tick -= CONVEY_TICKS
    if tick < BRAKE_TICKS:
        return BELT_SPEED * (
            1.0 - smoothstep(float(tick + 1) / BRAKE_TICKS)
        )
    return 0.0


def _lerp_targets(
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
    fraction: float,
) -> tuple[tuple[float, ...], ...]:
    return tuple(
        tuple(
            start_value + (end_value - start_value) * fraction
            for start_value, end_value in zip(
                start_hand, end_hand, strict=True
            )
        )
        for start_hand, end_hand in zip(start, end, strict=True)
    )


def _transition(
    tick: int,
    duration: int,
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    fraction = smoothstep(float(tick + 1) / duration)
    return _lerp_targets(start, end, fraction)


def _pivot_roll_transition(
    tick: int,
    duration: int,
    start: tuple[tuple[float, ...], ...],
    end: tuple[tuple[float, ...], ...],
) -> tuple[tuple[float, ...], ...]:
    """Roll each wrist through 180 degrees about a fixed fingertip point."""
    fraction = smoothstep(float(tick + 1) / duration)
    targets = []
    for start_hand, end_hand in zip(start, end, strict=True):
        roll_delta = end_hand[3] - start_hand[3]
        angle = roll_delta * fraction
        cosine = math.cos(angle)
        sine = math.sin(angle)
        pivot_y = 0.5 * (start_hand[1] + end_hand[1])
        pivot_z = 0.5 * (start_hand[2] + end_hand[2])
        offset_y = pivot_y - start_hand[1]
        offset_z = pivot_z - start_hand[2]
        rotated_y = cosine * offset_y - sine * offset_z
        rotated_z = sine * offset_y + cosine * offset_z
        linear = tuple(
            start_value + (end_value - start_value) * fraction
            for start_value, end_value in zip(
                start_hand, end_hand, strict=True
            )
        )
        targets.append(
            (
                linear[0],
                pivot_y - rotated_y,
                pivot_z - rotated_z,
                linear[3],
                linear[4],
                linear[5],
            )
        )
    return tuple(targets)


def hand_stage_targets_at_tick(
    tick: int,
) -> tuple[tuple[float, ...], ...]:
    tick = max(0, int(tick))
    if tick < DROP_SETTLE_TICKS:
        return HAND_STAGE_HOME_TARGETS
    tick -= DROP_SETTLE_TICKS
    if tick < FLIP_APPROACH_TICKS:
        return _transition(
            tick,
            FLIP_APPROACH_TICKS,
            HAND_STAGE_HOME_TARGETS,
            HAND_STAGE_FLIP_APPROACH_TARGETS,
        )
    tick -= FLIP_APPROACH_TICKS
    if tick < FLIP_GRIP_TICKS:
        return _transition(
            tick,
            FLIP_GRIP_TICKS,
            HAND_STAGE_FLIP_APPROACH_TARGETS,
            HAND_STAGE_FLIP_GRIP_TARGETS,
        )
    tick -= FLIP_GRIP_TICKS
    if tick < FLIP_LIFT_TICKS:
        return _transition(
            tick,
            FLIP_LIFT_TICKS,
            HAND_STAGE_FLIP_GRIP_TARGETS,
            HAND_STAGE_FLIP_LIFT_TARGETS,
        )
    tick -= FLIP_LIFT_TICKS
    if tick < FLIP_ROTATE_TICKS:
        return _pivot_roll_transition(
            tick,
            FLIP_ROTATE_TICKS,
            HAND_STAGE_FLIP_LIFT_TARGETS,
            HAND_STAGE_FLIPPED_LIFT_TARGETS,
        )
    tick -= FLIP_ROTATE_TICKS
    if tick < FLIP_PLACE_TICKS:
        return _transition(
            tick,
            FLIP_PLACE_TICKS,
            HAND_STAGE_FLIPPED_LIFT_TARGETS,
            HAND_STAGE_FLIP_PLACE_TARGETS,
        )
    tick -= FLIP_PLACE_TICKS
    if tick < FLIP_RELEASE_TICKS:
        return _transition(
            tick,
            FLIP_RELEASE_TICKS,
            HAND_STAGE_FLIP_PLACE_TARGETS,
            HAND_STAGE_FLIP_RELEASE_TARGETS,
        )
    tick -= FLIP_RELEASE_TICKS
    if tick < FLIP_CLEAR_TICKS:
        return _transition(
            tick,
            FLIP_CLEAR_TICKS,
            HAND_STAGE_FLIP_RELEASE_TARGETS,
            HAND_STAGE_FLIP_CLEAR_TARGETS,
        )
    tick -= FLIP_CLEAR_TICKS
    if tick < REORIENT_TICKS:
        return _transition(
            tick,
            REORIENT_TICKS,
            HAND_STAGE_FLIP_CLEAR_TARGETS,
            HAND_STAGE_REORIENT_TARGETS,
        )
    tick -= REORIENT_TICKS
    if tick < PUSH_APPROACH_TICKS:
        return _transition(
            tick,
            PUSH_APPROACH_TICKS,
            HAND_STAGE_REORIENT_TARGETS,
            HAND_STAGE_PUSH_APPROACH_TARGETS,
        )
    tick -= PUSH_APPROACH_TICKS
    if tick < PUSH_TICKS:
        return _transition(
            tick,
            PUSH_TICKS,
            HAND_STAGE_PUSH_APPROACH_TARGETS,
            HAND_STAGE_PUSH_TARGETS,
        )
    tick -= PUSH_TICKS
    if tick < PUSH_RELEASE_TICKS:
        return HAND_STAGE_PUSH_TARGETS
    tick -= PUSH_RELEASE_TICKS
    if tick < PUSH_CLEAR_TICKS:
        return _transition(
            tick,
            PUSH_CLEAR_TICKS,
            HAND_STAGE_PUSH_TARGETS,
            HAND_STAGE_PUSH_CLEAR_TARGETS,
        )
    return HAND_STAGE_PUSH_CLEAR_TARGETS


def finger_close_fraction_at_tick(tick: int) -> float:
    tick = max(0, int(tick))
    if tick < DROP_SETTLE_TICKS + FLIP_APPROACH_TICKS:
        return 0.0
    tick -= DROP_SETTLE_TICKS + FLIP_APPROACH_TICKS
    if tick < FLIP_GRIP_TICKS:
        return FLIP_FINGER_CLOSE_FRACTION * smoothstep(
            float(tick + 1) / FLIP_GRIP_TICKS
        )
    tick -= FLIP_GRIP_TICKS
    hold_ticks = FLIP_LIFT_TICKS + FLIP_ROTATE_TICKS + FLIP_PLACE_TICKS
    if tick < hold_ticks:
        return FLIP_FINGER_CLOSE_FRACTION
    tick -= hold_ticks
    if tick < FLIP_RELEASE_TICKS:
        return FLIP_FINGER_CLOSE_FRACTION * (
            1.0 - smoothstep(float(tick + 1) / FLIP_RELEASE_TICKS)
        )
    tick -= FLIP_RELEASE_TICKS + FLIP_CLEAR_TICKS + REORIENT_TICKS
    if tick < 0:
        return 0.0
    if tick < PUSH_APPROACH_TICKS:
        return PUSH_FINGER_CLOSE_FRACTION * smoothstep(
            float(tick + 1) / PUSH_APPROACH_TICKS
        )
    tick -= PUSH_APPROACH_TICKS
    if tick < PUSH_TICKS:
        return PUSH_FINGER_CLOSE_FRACTION
    tick -= PUSH_TICKS
    if tick < PUSH_RELEASE_TICKS:
        return PUSH_FINGER_CLOSE_FRACTION * (
            1.0 - smoothstep(float(tick + 1) / PUSH_RELEASE_TICKS)
        )
    return 0.0


def hand_controls_at_tick(tick: int) -> tuple[tuple[float, ...], ...]:
    stage_targets = hand_stage_targets_at_tick(tick)
    close_fraction = finger_close_fraction_at_tick(tick)
    finger_targets = tuple(
        value * close_fraction for value in LEAP_FINGER_CLOSE_TARGETS
    )
    return tuple(stage + finger_targets for stage in stage_targets)


def cycle_phase(tick: int) -> str:
    tick = max(0, int(tick))
    if tick < DROP_SETTLE_TICKS:
        return "drop_settle"
    tick -= DROP_SETTLE_TICKS
    if tick < FLIP_APPROACH_TICKS:
        return "flip_approach"
    tick -= FLIP_APPROACH_TICKS
    if tick < FLIP_GRIP_TICKS:
        return "flip_grip"
    tick -= FLIP_GRIP_TICKS
    if tick < FLIP_LIFT_TICKS:
        return "flip_lift"
    tick -= FLIP_LIFT_TICKS
    if tick < FLIP_ROTATE_TICKS:
        return "flip_rotate"
    tick -= FLIP_ROTATE_TICKS
    if tick < FLIP_PLACE_TICKS:
        return "flip_place"
    tick -= FLIP_PLACE_TICKS
    if tick < FLIP_RELEASE_TICKS:
        return "flip_release"
    tick -= FLIP_RELEASE_TICKS
    if tick < FLIP_CLEAR_TICKS:
        return "flip_clear"
    tick -= FLIP_CLEAR_TICKS
    if tick < REORIENT_TICKS:
        return "reorient"
    tick -= REORIENT_TICKS
    if tick < PUSH_APPROACH_TICKS:
        return "push_approach"
    tick -= PUSH_APPROACH_TICKS
    if tick < PUSH_TICKS:
        return "push"
    tick -= PUSH_TICKS
    if tick < PUSH_RELEASE_TICKS:
        return "push_release"
    tick -= PUSH_RELEASE_TICKS
    if tick < PUSH_CLEAR_TICKS:
        return "push_clear"
    return "settle"
